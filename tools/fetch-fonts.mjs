#!/usr/bin/env node
/* One-off helper: downloads the Google Fonts WOFF2 files used by the site
   (latin + arabic subsets only) into fonts/web/ and writes css/fonts.css.
   Lato, Montserrat and Cairo are licensed under the SIL Open Font License,
   which permits self-hosting. Run: node tools/fetch-fonts.mjs */
import { writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const UA = 'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/120.0 Safari/537.36';
const q = 'family=Lato:wght@400;700&family=Montserrat:wght@400;700&family=Cairo:wght@400;600;700&display=swap';
const css = await (await fetch(`https://fonts.googleapis.com/css2?${q}`, { headers: { 'user-agent': UA } })).text();
const blocks = [...css.matchAll(/\/\*\s*([\w-]+)\s*\*\/\s*@font-face\s*{([^}]*)}/g)].map((m) => {
	const g = (re) => (m[2].match(re) || [])[1];
	return { subset: m[1], family: g(/font-family:\s*'([^']+)'/), weight: +g(/font-weight:\s*(\d+)/), url: g(/url\(([^)]+)\)/), range: g(/unicode-range:\s*([^;]+)/) };
}).filter((b) => b.subset === 'latin' || b.subset === 'arabic');
// merge weights that share one (variable) file
const byUrl = new Map();
for (const b of blocks) { const e = byUrl.get(b.url) || { ...b, weights: [] }; e.weights.push(b.weight); byUrl.set(b.url, e); }
mkdirSync(join(ROOT, 'fonts/web'), { recursive: true });
let out = '/* Self-hosted fonts (SIL OFL). Generated by tools/fetch-fonts.mjs. latin + arabic subsets only. */\n';
for (const e of byUrl.values()) {
	const w = [...new Set(e.weights)].sort((a, b) => a - b);
	const file = `${e.family.toLowerCase()}-${e.subset}${w.length > 1 && e.family !== 'Lato' ? '-var' : '-' + w[0]}.woff2`;
	writeFileSync(join(ROOT, 'fonts/web', file), Buffer.from(await (await fetch(e.url)).arrayBuffer()));
	const weight = w.length > 1 ? `${w[0]} ${w[w.length - 1]}` : `${w[0]}`;
	out += `@font-face{font-family:'${e.family}';font-style:normal;font-weight:${weight};font-display:swap;src:url(../fonts/web/${file}) format('woff2');unicode-range:${e.range}}\n`;
	console.log(file, weight);
}
writeFileSync(join(ROOT, 'css/fonts.css'), out);
